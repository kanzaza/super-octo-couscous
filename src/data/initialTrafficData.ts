export const parseRawCsv = (csvText: string): TrafficFineRecord[] => {
  const lines = csvText.split(/\r?\n/).filter(line => line.trim().length > 0);
  const records: TrafficFineRecord[] = [];
  
  let headerIndex = -1;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].includes("วันที่ชำระเงิน") && lines[i].includes("เลขที่ใบสั่ง")) {
      headerIndex = i;
      break;
    }
  }

  if (headerIndex === -1) {
    return records;
  }

  // Detect delimiter: tab (\t) or comma (,)
  const isTab = lines[headerIndex].includes("\t");
  const delimiter = isTab ? "\t" : ",";

  // Parse row respecting quoted fields
  const parseRow = (line: string, delim: string): string[] => {
    const result: string[] = [];
    let cur = "";
    let inQuotes = false;
    for (let i = 0; i < line.length; i++) {
      const char = line[i];
      if (char === '"') {
        if (inQuotes && line[i + 1] === '"') {
          cur += '"';
          i++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (char === delim && !inQuotes) {
        result.push(cur.trim());
        cur = "";
      } else {
        cur += char;
      }
    }
    result.push(cur.trim());
    return result;
  };

  for (let i = headerIndex + 1; i < lines.length; i++) {
    const cols = parseRow(lines[i], delimiter);
    if (cols.length < 6 || !cols[0] || !cols[2]) continue;

    const paymentDate = (cols[0] || "").trim();
    const ticketDate = (cols[1] || "").trim();
    const ticketNumber = (cols[2] || "").trim();
    const legalSection = (cols[3] || "").trim();
    const offense = (cols[4] || "").trim();
    const rawAmount = (cols[5] || "0").replace(/,/g, "").trim();
    const amount = parseFloat(rawAmount) || 0;
    const paymentChannel = (cols[6] || "KTB Mobile Banking").trim();
    const citizenId = (cols[7] || "").trim();
    const payerName = (cols[8] || "").trim();
    const helmetCode = (cols[9] || "-").trim();
    const officerName = (cols[10] || "-").trim();
    const actType = (cols[11] || "พ.ร.บ.รถยนต์").trim();

    records.push({
      id: `imported-${ticketNumber}-${i}`,
      paymentDate,
      ticketDate,
      ticketNumber,
      legalSection,
      offense,
      amount,
      paymentChannel,
      citizenId,
      payerName,
      helmetCode,
      officerName,
      actType
    });
  }

  return records;
};
